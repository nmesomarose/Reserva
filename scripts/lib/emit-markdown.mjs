/**
 * emit-markdown.mjs
 * ---------------------------------------------------------------------------
 * Renders `dist/TOKENS.md`: the reference a developer reads when they want to
 * know *which* variable to reach for, and a designer reads to see whether the
 * token set is complete.
 *
 * The document is generated, so it can never drift from `tokens.css`. It is
 * written for scanning: the roles table first, because that is the only tier
 * product code is allowed to use, and the primitives after it, clearly fenced
 * off as foundations.
 */

import { TYPOGRAPHY_PROPERTIES } from './format.mjs';

const LEVEL = { error: 'ERROR', warn: 'WARNING', info: 'NOTE' };
const LEVEL_ICON = { error: 'x', warn: '!', info: 'i' };

/**
 * @param {object} build
 * @param {object} options
 * @param {string} options.source
 * @returns {string} markdown
 */
export function emitMarkdown(build, { source }) {
  const { config, stats } = build;
  const lines = [];

  lines.push('# Design tokens');
  lines.push('');
  lines.push('> Generated by `npm run build` from `' + source + '`. Do not edit by hand.');
  lines.push('');
  lines.push(
    `${stats.variables} CSS custom properties from ${stats.tokens} tokens: ` +
      `**${stats.roles} colour roles**, **${stats.primitives} primitive colours**, ` +
      `${stats.spacing} spacing steps, ${stats.typographyStyles} text styles, ${stats.shadows} shadows.`,
  );
  lines.push('');

  /* ------------------------------------------------------------- how to use */
  lines.push('## The one rule: roles in, primitives out');
  lines.push('');
  lines.push('The colour model has two tiers, and only one of them is for product code.');
  lines.push('');
  lines.push('```');
  lines.push('  component  ->  --ds-color-primary            semantic role     USE THIS');
  lines.push('                     |');
  lines.push('                     +-> --ds-color-primitive-key-primary   foundation    not for components');
  lines.push('```');
  lines.push('');
  lines.push('| Tier | Prefix | Meaning | Allowed in components |');
  lines.push('| --- | --- | --- | --- |');
  lines.push('| Semantic roles | `--ds-color-*` | Intent: primary, error, on-primary-container. Stable across themes. | **Yes** |');
  lines.push('| Primitives | `--ds-color-primitive-*` | Raw palette steps and key colours. The source of truth the roles point at. | **No** |');
  lines.push('');
  lines.push(
    'A role is emitted as a `var()` reference to its primitive, so re-pointing one primitive ' +
      're-themes everything downstream. If a component reads a primitive directly, a future ' +
      'dark theme or rebrand has to be chased through the codebase.',
  );
  lines.push('');

  /* ---------------------------------------------------------- colour roles */
  lines.push('## Colour roles');
  lines.push('');
  lines.push(`${build.roles.length} roles. This is the complete list of colours a component may use.`);
  lines.push('');
  lines.push('| Role | CSS variable | Resolves to | Value |');
  lines.push('| --- | --- | --- | --- |');
  for (const role of build.roles) {
    if (role.derived) continue;
    lines.push(
      `| \`${role.tokenName}\` | \`${role.name}\` | ${role.aliasTarget ? `\`${role.aliasTarget}\`` : '_literal_'} | \`${role.colorHex ?? role.value}\` |`,
    );
  }
  lines.push('');

  lines.push('### Pairing and contrast');
  lines.push('');
  lines.push('Each `on ...` role is checked against the role it sits on (WCAG 2.1 contrast ratio).');
  lines.push('');
  lines.push('| Foreground | Background | Ratio | AA body text (4.5:1) | AA large text (3:1) |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const pair of build.pairs) {
    lines.push(
      `| \`${pair.onVariable}\` | \`${pair.baseVariable}\` | ${pair.ratio}:1 | ${mark(pair.passAA)} | ${mark(pair.passAALarge)} |`,
    );
  }
  lines.push('');

  /* ------------------------------------------------------------- primitives */
  lines.push('## Primitive colours');
  lines.push('');
  lines.push('> Foundations only. Do not reference these from components.');
  lines.push('');
  for (const palette of build.palettes) {
    const used = palette.usedByRoles.length;
    lines.push(`### ${palette.title}`);
    lines.push('');
    lines.push(
      used > 0
        ? `Referenced by ${used} role${used === 1 ? '' : 's'}.`
        : '**Not referenced by any role yet** - a foundation with no semantic entry point.',
    );
    lines.push('');
    lines.push('| Step | CSS variable | Value |');
    lines.push('| --- | --- | --- |');
    for (const step of palette.steps) {
      lines.push(`| ${step.step ?? '-'} | \`${step.variable}\` | \`${step.hex ?? ''}\` |`);
    }
    lines.push('');
    lines.push(`Figma path: \`${palette.key}\``);
    lines.push('');
  }

  lines.push('Each palette above is followed by its Figma path so a value can be traced back to the source file.');
  lines.push('');
  lines.push('Palettes that no role references are listed with a warning: they are foundations with no semantic entry point yet.');
  lines.push('');

  /* ---------------------------------------------------------------- spacing */
  lines.push('## Spacing');
  lines.push('');
  lines.push('| Step | CSS variable | Value |');
  lines.push('| --- | --- | --- |');
  for (const entry of build.spacing) {
    if (entry.derived) continue;
    lines.push(`| \`${entry.tokenName}\` | \`${entry.name}\` | \`${entry.value}\` |`);
  }
  lines.push('');

  /* ------------------------------------------------------------- typography */
  lines.push('## Typography');
  lines.push('');
  lines.push('One variable per CSS property, plus a `font` shorthand per style.');
  lines.push('');
  lines.push('| Style | font-size | line-height | font-weight | letter-spacing |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const style of build.typography) {
    const find = (property) => style.variables.find((v) => v.cssProperty === property && v.derived !== 'shorthand')?.value ?? '';
    lines.push(
      `| \`${style.name}\` | \`${find('font-size')}\` | \`${find('line-height')}\` | \`${find('font-weight')}\` | \`${find('letter-spacing')}\` |`,
    );
  }
  lines.push('');
  lines.push('### Applying a text style');
  lines.push('');
  lines.push('```css');
  const example = build.typography[0];
  if (example) {
    const family = example.variables.find((v) => v.cssProperty === 'font-family')?.value;
    if (family) lines.push(`:root { --my-font-family: ${family}; }`);
    const shorthand = example.variables.find((v) => v.cssProperty === 'font');
    if (shorthand) lines.push(`.prose { font: var(${shorthand.name}); }`);
  }
  lines.push('```');
  lines.push('');
  lines.push('### Token property to CSS property mapping');
  lines.push('');
  lines.push('| Figma property | CSS property | Note |');
  lines.push('| --- | --- | --- |');
  for (const [key, spec] of Object.entries(TYPOGRAPHY_PROPERTIES)) {
    lines.push(`| \`${key}\` | \`${spec.property}\` | ${typographyNote(key)} |`);
  }
  lines.push('');

  /* ---------------------------------------------------------------- shadows */
  lines.push('## Shadows');
  lines.push('');
  lines.push('| Token | CSS variable | box-shadow |');
  lines.push('| --- | --- | --- |');
  for (const entry of build.shadows) {
    lines.push(`| \`${entry.tokenName}\` | \`${entry.name}\` | \`${entry.value}\` |`);
  }
  lines.push('');
  lines.push('Figma "radius" maps to the CSS blur radius, and a non-zero spread is passed through.');
  lines.push('');

  /* ---------------------------------------------------------------- findings */
  const findings = ordered(build.warnings);
  lines.push('## Findings from the last build');
  lines.push('');
  if (findings.length === 0) {
    lines.push('No findings. The token set is internally consistent.');
  } else {
    lines.push(`${findings.length} finding${findings.length === 1 ? '' : 's'}.`);
    lines.push('');
    lines.push('| | Level | Token | Finding |');
    lines.push('| --- | --- | --- | --- |');
    for (const finding of findings) {
      lines.push(
        `| ${LEVEL_ICON[finding.level]} | ${LEVEL[finding.level]} | \`${finding.token}\` | ${escapePipes(finding.message)} |`,
      );
    }
  }
  lines.push('');

  /* ------------------------------------------------------------------ config */
  lines.push('## Build configuration');
  lines.push('');
  lines.push('| Option | Value |');
  lines.push('| --- | --- |');
  lines.push(`| prefix | \`${config.prefix}\` |`);
  lines.push(`| colour format | \`${config.colorFormat}\` |`);
  lines.push(`| role values | \`${config.roleValues}\` |`);
  lines.push(`| unit | \`${config.unit}\` |`);
  lines.push(`| channel companions | \`${config.channels}\` |`);
  lines.push(`| font shorthand | \`${config.fontShorthand}\` |`);
  lines.push('');
  lines.push('See `README.md` for the full option list and the rationale behind each one.');
  lines.push('');

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/* ------------------------------------------------------------------ helpers */

const mark = (pass) => (pass ? 'pass' : '**FAIL**');
const escapePipes = (text) => text.replace(/\|/g, '\\|');
const ordered = (warnings) =>
  [...warnings].sort((a, b) => {
    const rank = { error: 0, warn: 1, info: 2 };
    return rank[a.level] - rank[b.level] || String(a.token).localeCompare(String(b.token));
  });

function typographyNote(key) {
  switch (key) {
    case 'textCase':
      return 'Figma text case mapped to `text-transform`.';
    case 'paragraphSpacing':
      return 'Figma paragraph spacing has no direct CSS equivalent; mapped to `margin`.';
    case 'paragraphIndent':
      return 'Applied to the first line of a paragraph.';
    case 'fontStretch':
      return 'Only meaningful for variable fonts.';
    default:
      return '';
  }
}
